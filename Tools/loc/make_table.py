"""Builds Source/DanmakuSTG/DanmakuText_Table.inl from Tools/loc/en.txt ("zh<TAB>en" per line).

    python Tools/loc/make_table.py              -> regenerate the table
    python Tools/loc/make_table.py --from-index -> first merge en_index.txt (line numbers of zh.txt) into en.txt
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "Source", "DanmakuSTG", "DanmakuText_Table.inl")


def read_pairs():
    pairs = {}
    p = os.path.join(HERE, "en.txt")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            line = line.rstrip("\n")
            if "\t" in line:
                zh, en = line.split("\t", 1)
                pairs[zh] = en
    return pairs


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


if __name__ == "__main__":
    pairs = read_pairs()
    if "--from-index" in sys.argv:
        zh = open(os.path.join(HERE, "zh.txt"), encoding="utf-8").read().split("\n")
        for line in open(os.path.join(HERE, "en_index.txt"), encoding="utf-8"):
            line = line.rstrip("\n")
            if "\t" not in line:
                continue
            n, en = line.split("\t", 1)
            if en.strip() == "-":
                continue
            pairs[zh[int(n) - 1]] = en
        with open(os.path.join(HERE, "en.txt"), "w", encoding="utf-8") as f:
            for k, v in pairs.items():
                f.write(k + "\t" + v + "\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by Tools/loc/make_table.py from Tools/loc/en.txt. Do not edit by hand.\n")
        for k, v in pairs.items():
            f.write('{ TEXT("%s"), TEXT("%s") },\n' % (esc(k), esc(v)))
    print(len(pairs), "entries")

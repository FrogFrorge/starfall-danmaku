"""Merge the translations (out_<lang>_*.json, keyed by source.json ids) into Godot/Scripts/TextJa.cs and TextFr.cs,
and convert every Chinese string to Simplified Chinese (OpenCC tw2s) into TextZhs.cs.

Run after prepare.py and the translation passes. Strings missing from a language fall back to English in game.
"""
import glob, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(HERE, "..", "..", "..", "Godot", "Scripts")
src = {str(x["id"]): x for x in json.load(io.open(os.path.join(HERE, "source.json"), encoding="utf-8"))}


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


sys.stdout.reconfigure(encoding="utf-8")
for lang, cls, name in (("ja", "Ja", "Japanese"), ("fr", "Fr", "French")):
    tr = {}
    for f in sorted(glob.glob(os.path.join(HERE, f"out_{lang}_*.json"))):
        tr.update(json.load(io.open(f, encoding="utf-8")))
    extra = os.path.join(HERE, f"extra_{lang}.json")   # hand-added strings, keyed by the Chinese
    pairs = [(src[k]["zh"], v) for k, v in sorted(tr.items(), key=lambda kv: int(kv[0])) if k in src and v.strip()]
    if lang == "fr":
        # the CJK font draws the curly apostrophe full-width, which leaves a gap ("qu’ il"): use the straight one
        pairs = [(z, t.replace("’", "'")) for z, t in pairs]
    if os.path.exists(extra):
        pairs += list(json.load(io.open(extra, encoding="utf-8")).items())
    missing = [k for k in src if k not in tr]
    lines = [f"// Generated by Tools/loc/i18n/build.py from source.json + out_{lang}_*.json. Chinese -> {name}.",
             "namespace DanmakuSTG;", "", "public static partial class Danmaku", "{",
             f"\tstatic readonly (string Zh, string T)[] GTable{cls} =", "\t{"]
    lines += [f"\t\t({cs(z)}, {cs(t)})," for z, t in pairs]
    lines += ["\t};", "}", ""]
    io.open(os.path.join(SCRIPTS, f"Text{cls}.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(lang, len(pairs), "strings,", len(missing), "missing")

# Simplified Chinese: every string the game knows (Saved/AllText.tsv), converted character by character
from opencc import OpenCC
cc = OpenCC("tw2s")
alltext = os.path.join(HERE, "..", "..", "..", "Godot", "Saved", "AllText.tsv")
keys = [l.split("\t")[0] for l in io.open(alltext, encoding="utf-8") if l.strip()]
pairs = [(z, cc.convert(z)) for z in keys if cc.convert(z) != z]
lines = ["// Generated by Tools/loc/i18n/build.py (OpenCC tw2s). Traditional -> Simplified Chinese; strings that are",
         "// the same in both scripts are left out (Tr falls back to the Chinese itself).",
         "namespace DanmakuSTG;", "", "public static partial class Danmaku", "{",
         "\tstatic readonly (string Zh, string T)[] GTableZhs =", "\t{"]
lines += [f"\t\t({cs(z)}, {cs(t)})," for z, t in pairs]
lines += ["\t};", "}", ""]
io.open(os.path.join(SCRIPTS, "TextZhs.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("zhs", len(pairs), "strings")
